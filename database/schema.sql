-- Food Redistribution System (FRS)
-- PostgreSQL Database Schema

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL
        CHECK (role IN ('donor', 'ngo', 'volunteer', 'admin')),
    org_type VARCHAR(100) DEFAULT NULL,
    phone VARCHAR(50) NOT NULL,
    address TEXT NOT NULL,
    pincode VARCHAR(20) NOT NULL,
    is_verified BOOLEAN DEFAULT FALSE,
    is_active BOOLEAN DEFAULT TRUE,
    reset_token VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS verification_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    status VARCHAR(50) NOT NULL
        CHECK (status IN ('pending', 'approved', 'rejected')),
    notes TEXT DEFAULT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS donations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id INTEGER NOT NULL,
    food_name VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    quantity VARCHAR(100) NOT NULL,
    contains_allergens TEXT DEFAULT NULL,
    mfd_datetime TIMESTAMP NOT NULL,
    exp_datetime TIMESTAMP NOT NULL,
    pickup_address TEXT NOT NULL,
    pickup_pincode VARCHAR(20) NOT NULL,
    pickup_window VARCHAR(255) NOT NULL,
    photo_url TEXT DEFAULT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'posted'
        CHECK (status IN (
            'posted', 'claimed', 'picked_up', 'completed', 'expired'
        )),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (donor_id)
        REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS claims (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donation_id INTEGER UNIQUE NOT NULL,
    ngo_id INTEGER NOT NULL,
    volunteer_id INTEGER DEFAULT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'claimed'
        CHECK (status IN (
            'claimed', 'in_transit', 'delivered', 'cancelled'
        )),
    delivery_notes TEXT DEFAULT NULL,
    claimed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMP DEFAULT NULL,
    FOREIGN KEY (donation_id)
        REFERENCES donations(id) ON DELETE CASCADE,
    FOREIGN KEY (ngo_id)
        REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (volunteer_id)
        REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS notifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS issues (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id INTEGER NOT NULL,
    donation_id INTEGER DEFAULT NULL,
    claim_id INTEGER DEFAULT NULL,
    subject VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'open'
        CHECK (status IN (
            'open', 'under_review', 'resolved', 'dismissed'
        )),
    admin_notes TEXT DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (reporter_id)
        REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (donation_id)
        REFERENCES donations(id) ON DELETE SET NULL,
    FOREIGN KEY (claim_id)
        REFERENCES claims(id) ON DELETE SET NULL
);

-- Performance and Foreign Key Indexes for PostgreSQL
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_pincode ON users(pincode);
CREATE INDEX IF NOT EXISTS idx_verification_user ON verification_records(user_id);
CREATE INDEX IF NOT EXISTS idx_donations_donor ON donations(donor_id);
CREATE INDEX IF NOT EXISTS idx_donations_pincode_status ON donations(pickup_pincode, status);
CREATE INDEX IF NOT EXISTS idx_donations_exp ON donations(exp_datetime);
CREATE INDEX IF NOT EXISTS idx_claims_ngo ON claims(ngo_id);
CREATE INDEX IF NOT EXISTS idx_claims_volunteer ON claims(volunteer_id);
CREATE INDEX IF NOT EXISTS idx_claims_donation ON claims(donation_id);
CREATE INDEX IF NOT EXISTS idx_notifications_user_unread ON notifications(user_id, is_read);
CREATE INDEX IF NOT EXISTS idx_issues_reporter ON issues(reporter_id);